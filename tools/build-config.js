// Builds src/pkjs/config-page.js: the settings page (config/config-page.html) with the shared
// modules from src/common and every data-source plug-in from src/sources inlined, so the phone can open
// it as a data: URI (CONTRACTS.md §10).
//
// The modules are wrapped in a tiny CommonJS shim. Module ids are root-relative paths without `.js`
// (e.g. 'src/sources/metrotransit/index'); require() resolves './x' / '../x' against the requiring
// module's directory and also tries '<id>/index'. Exposed as
// window.BusWatch = {geo, settings, ranking, optimize, directions, format, registry}
// with registry = createRegistry(require('src/sources/all')).
//
// usage: node tools/build-config.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const COMMON = ['geo', 'settings', 'view', 'catalog', 'federation', 'ranking', 'optimize', 'directions', 'format'];
const MODULES_MARKER = '<!--BUSWATCH-MODULES-->';
const PARAMS_MARKER = '<!--PARAMS-->';

function fail(msg) {
  console.error('build-config: ' + msg);
  process.exit(1);
}

function walk(dir) {
  const out = [];
  for (const f of fs.readdirSync(path.join(root, dir), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = dir + '/' + f.name;
    if (f.isDirectory()) out.push(...walk(rel));
    else if (f.name.endsWith('.js')) out.push(rel);
  }
  return out;
}

const missing = COMMON.filter(m => !fs.existsSync(path.join(root, 'src/common', m + '.js')));
if (missing.length) fail('missing ' + missing.map(m => 'src/common/' + m + '.js').join(', ') + ' (needed by the settings page)');
if (!fs.existsSync(path.join(root, 'src/sources/all.js'))) fail('missing src/sources/all.js');

const files = COMMON.map(m => 'src/common/' + m + '.js').concat(walk('src/sources'));
const ids = new Set(files.map(f => f.replace(/\.js$/, '')));

// every relative require must resolve inside the bundle (fail at build time, not on the phone)
function resolveId(from, name) {
  let id = name.replace(/\.js$/, '');
  if (id.startsWith('.')) id = path.posix.normalize(path.posix.join(path.posix.dirname(from), id));
  if (ids.has(id)) return id;
  if (ids.has(id + '/index')) return id + '/index';
  return null;
}
for (const f of files) {
  const src = fs.readFileSync(path.join(root, f), 'utf8');
  for (const m of src.matchAll(/require\(\s*['"]([^'"]+)['"]\s*\)/g)) {
    if (!resolveId(f.replace(/\.js$/, ''), m[1])) fail(f + ": require('" + m[1] + "') is not bundled");
  }
}

// code inside a <script> element must not close it or open an HTML comment
const scriptSafe = js => js.replace(/<\/(script)/gi, '<\\/$1').replace(/<!--/g, '<\\!--');

const defs = files.map(f => {
  const src = fs.readFileSync(path.join(root, f), 'utf8');
  return 'defs[' + JSON.stringify(f.replace(/\.js$/, '')) + '] = function (module, exports, require) {\n' + src + '\n};';
}).join('\n');

const bundle = [
  '<script>',
  '(function () {',
  '  var defs = {}, cache = {};',
  '  function normalize(parts) {',
  '    var out = [];',
  '    for (var i = 0; i < parts.length; i++) {',
  "      if (parts[i] === '' || parts[i] === '.') continue;",
  "      if (parts[i] === '..') out.pop(); else out.push(parts[i]);",
  '    }',
  "    return out.join('/');",
  '  }',
  '  function resolve(from, name) {',
  "    var id = String(name).replace(/\\.js$/, '');",
  "    if (id.charAt(0) === '.') id = normalize(from.split('/').slice(0, -1).concat(id.split('/')));",
  '    if (defs.hasOwnProperty(id)) return id;',
  "    if (defs.hasOwnProperty(id + '/index')) return id + '/index';",
  "    throw new Error('module not bundled: ' + name);",
  '  }',
  '  function load(id) {',
  '    if (cache.hasOwnProperty(id)) return cache[id].exports;',
  '    var module = { exports: {} };',
  '    cache[id] = module;',
  '    defs[id](module, module.exports, function (name) { return load(resolve(id, name)); });',
  '    return module.exports;',
  '  }',
  scriptSafe(defs),
  '  window.BusWatch = {',
  COMMON.map(m => '    ' + m + ": load('src/common/" + m + "'),").join('\n'),
  "    registry: load('src/sources/registry').createRegistry(load('src/sources/all'))",
  '  };',
  '})();',
  '</script>',
].join('\n');

let html = fs.readFileSync(path.join(root, 'config/config-page.html'), 'utf8');
if (!html.includes(MODULES_MARKER)) fail('config/config-page.html has no ' + MODULES_MARKER + ' marker');
if (!/<head>[\s\S]*<!--PARAMS-->[\s\S]*<\/head>/.test(html)) fail('config/config-page.html needs ' + PARAMS_MARKER + ' inside <head>');
html = html.replace(MODULES_MARKER, () => bundle); // function: no $-pattern expansion

const out = '// GENERATED by tools/build-config.js from config/config-page.html - do not edit.\n' +
  'module.exports = ' + JSON.stringify(html) + ';\n';
fs.writeFileSync(path.join(root, 'src/pkjs/config-page.js'), out);
console.log('config page: ' + (html.length / 1024).toFixed(1) + ' KB html, module ' + (out.length / 1024).toFixed(1) + ' KB');
